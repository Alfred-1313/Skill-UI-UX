#!/bin/bash
# Rebuild portable instructions and installable skill archives from skills/.
set -euo pipefail
cd "$(dirname "$0")"
command -v python3 >/dev/null || { echo "python3 is required to package skills" >&2; exit 1; }
body() { awk 'BEGIN{n=0} /^---$/{n++; next} n>=2{print}' "$1"; }
{
  echo "# Bot builder instructions"
  echo
  echo "<!-- Generated by build.sh from skills/*/SKILL.md - edit those, then run ./build.sh -->"
  echo
  echo "Use the builder's preferences for this project; apply Telegram-specific modules only when relevant. Explicit user requests and project requirements take precedence over inferred defaults."
  echo "All references are included as Reference sections below. If you copied only this file, use those inline sections instead of requiring the source paths."
  echo
  body skills/bot-builder-style/SKILL.md | sed 's#`references/#`skills/bot-builder-style/references/#g'
  echo
  sed '1s/^# /## Reference: /' skills/bot-builder-style/references/design-profile.md
  echo
  echo "---"
  echo
  body skills/telegram-bot-customization/SKILL.md | sed 's#`references/#`skills/telegram-bot-customization/references/#g'
  echo
  echo "---"
  echo
  for ref in checklist data-model admin-screens web-panel content-editing bot-stats status-reports self-update; do
    echo
    echo "---"
    echo
    sed '1s/^# /## Reference: /' "skills/telegram-bot-customization/references/$ref.md"
  done
} > AGENTS.md
cp AGENTS.md GEMINI.md
mkdir -p .github && cp AGENTS.md .github/copilot-instructions.md
echo "AGENTS.md, GEMINI.md and .github/copilot-instructions.md rebuilt ($(wc -l < AGENTS.md) lines)"
python3 - <<'PY'
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

root = Path('skills')
Path('dist').mkdir(exist_ok=True)
for skill in sorted(root.iterdir()):
    if not (skill / 'SKILL.md').is_file():
        continue
    target = Path('dist') / (skill.name + '.skill')
    with ZipFile(target, 'w', compression=ZIP_DEFLATED) as archive:
        for path in sorted(skill.rglob('*')):
            if not path.is_file() or path.suffix != '.md':
                continue
            # Fixed metadata makes repeated builds produce identical archives.
            info = ZipInfo(path.relative_to(root).as_posix(), (1980, 1, 1, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            archive.writestr(info, path.read_bytes())
    print(f'{target} rebuilt')
PY
