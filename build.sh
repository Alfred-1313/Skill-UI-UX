#!/bin/bash
# Rebuilds AGENTS.md (for Codex, Cursor, Gemini CLI, Copilot, Windsurf, Aider...) from the two
# skills, so the skills stay the single source. Run it after editing anything under skills/.
set -e
cd "$(dirname "$0")"
body() { awk 'BEGIN{n=0} /^---$/{n++; next} n>=2{print}' "$1"; }
{
  echo "# Bot builder instructions"
  echo
  echo "<!-- Generated by build.sh from skills/*/SKILL.md - edit those, then run ./build.sh -->"
  echo
  echo "Follow both parts below in every task on this project."
  echo
  body skills/bot-builder-style/SKILL.md
  echo
  echo "---"
  echo
  body skills/telegram-bot-customization/SKILL.md | sed 's#`references/#`skills/telegram-bot-customization/references/#g'
  echo
  echo "---"
  echo
  for ref in checklist data-model admin-screens web-panel bot-stats self-update; do
    echo
    echo "---"
    echo
    sed '1s/^# /## Reference: /' "skills/telegram-bot-customization/references/$ref.md"
  done
} > AGENTS.md
cp AGENTS.md GEMINI.md
mkdir -p .github && cp AGENTS.md .github/copilot-instructions.md
echo "AGENTS.md, GEMINI.md and .github/copilot-instructions.md rebuilt ($(wc -l < AGENTS.md) lines)"
